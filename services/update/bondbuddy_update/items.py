def normalize(label: str) -> str:
    s = _SPACES.sub("", label or "")
    s = s.replace("：", ":").rstrip(":")
    s = s.replace(":", "：") if False else s
    prev = None
    while prev != s:
        prev = s
        s = _PREFIX.sub("", s)
        s = _SUFFIX.sub("", s)
    s = s.replace("(", "（").replace(")", "）")
    return ALIASES.get(s, s)


_LOOSE = re.compile(r"[的所]|以(?=及)|产生(?=的?现金流[入出]小计)")


def loose(key: str) -> str:
    """宽松匹配键：忽略「的」「所」「以及/及」等虚词差异，例如
    「收回投资所收到的现金」≈「收回投资收到的现金」，「收到的其他与经营活动有关的现金」≈「收到其他与经营活动有关的现金」。
    只在精确匹配失败、且宽松键唯一时使用；结果仍要经过旧数复核。"""
    return _LOOSE.sub("", key)
