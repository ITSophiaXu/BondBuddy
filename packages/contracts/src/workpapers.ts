import {Type,type Static} from '@sinclair/typebox';
import {M4MaterialPinSchema,M4_DOCUMENT_FIXED_PRICE,type M4ArtifactPin} from './m4-workspace.js';
import type {ProjectFileSource} from './project-file-workspace.js';
const obj=<T extends Parameters<typeof Type.Object>[0]>(p:T)=>Type.Object(p,{additionalProperties:false});
const id=Type.String({minLength:1,maxLength:128});
import {WORKPAPER_LIMITS,type WorkpaperEntry} from './workpaper-entry.js';
export * from './workpaper-entry.js';
export const WorkpaperImportSchema=obj({request_id:id,material:M4MaterialPinSchema});
export const WorkpaperStartSchema=obj({request_id:id,catalogue_id:id,catalogue_sha256:Type.String({pattern:'^[a-f0-9]{64}$'}),
  item_ids:Type.Array(id,{minItems:1,maxItems:WORKPAPER_LIMITS.items,uniqueItems:true}),source_version_id:id,
  source_selection_revision:Type.Integer({minimum:0}),requirements:Type.String({maxLength:12000}),
  price_version:id,expected_points:Type.Integer({minimum:1})});
export type WorkpaperStart=Static<typeof WorkpaperStartSchema>;
export const WorkpaperActionSchema=obj({action:Type.Union([Type.Literal('pause'),Type.Literal('resume'),Type.Literal('retry_failed'),Type.Literal('cancel')]),expected_revision:Type.Integer({minimum:1})});
export const WORKPAPER_PRICE=M4_DOCUMENT_FIXED_PRICE;
export type WorkpaperCatalogue={catalogue_id:string;sha256:string;filename:string;entries:WorkpaperEntry[];warnings:string[];created_at:string};
export type WorkpaperItem={entry:WorkpaperEntry;run_id:string|null;state:string;stage:string|null;attempt:number;error:string|null;
  artifacts:{kind:'document'|'preparation_note';filename:string;pin:M4ArtifactPin}[]};
export type WorkpaperBatch={batch_id:string;topic_id:string;catalogue_id:string;state:'queued'|'running'|'paused'|'complete'|'partial'|'cancelled';revision:number;
  source:ProjectFileSource;items:WorkpaperItem[];total_points:number;charged_points:number;created_at:string;error:string|null};
export type WorkpaperWorkspace={catalogues:WorkpaperCatalogue[];batches:WorkpaperBatch[]};

/** Paths are generated by the server, never interpreted as local filesystem paths. */
export function workpaperPathPart(value:string){
  const clean=value.normalize('NFKC').replace(/[\\/:*?"<>|\u0000-\u001f\u007f]/g,'_').replace(/[. ]+$/g,'').trim().slice(0,100);
  return !clean||/^\.+$/.test(clean)?'未命名':/^(CON|PRN|AUX|NUL|COM[1-9]|LPT[1-9])(?:\.|$)/i.test(clean)?'_'+clean:clean;
}
export function workpaperOpenApiPaths(){
  const base='/api/v1/projects/{project_id}/workpapers';
  const route=(schema?:unknown,batch=false)=>({security:[{sessionCookie:[]}],parameters:(batch?['project_id','batch_id']:['project_id']).map(name=>({name,in:'path',required:true,schema:{type:'string'}})),
    ...(schema?{requestBody:{required:true,content:{'application/json':{schema}}}}:{}),responses:{200:{description:'Owner-scoped workpaper catalogue or batch'},404:{description:'Not found'}}});
  return {[base]:{get:route()},[base+'/catalogues']:{post:route(WorkpaperImportSchema)},[base+'/batches']:{post:route(WorkpaperStartSchema)},
    [base+'/batches/{batch_id}/actions']:{post:route(WorkpaperActionSchema,true)},[base+'/batches/{batch_id}/download']:{get:route(undefined,true)}};
}
