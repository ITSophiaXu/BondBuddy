import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import ts from '../../../../node_modules/typescript/lib/typescript.js';
const root=new URL('../../../../',import.meta.url),out=new URL('./',import.meta.url);
const sha=b=>createHash('sha256').update(b).digest('hex');
const read=p=>readFileSync(new URL(p,root));
const sourceCommit=execFileSync('git',['rev-parse','HEAD'],{cwd:fileURLToPath(root),encoding:'utf8'}).trim();
const modules=['apps/api/src/evidence-gate.ts','apps/worker/src/execution-node-runtime.ts','apps/worker/src/managed-database-preflight.ts'];
const files=modules.map(path=>{
 const source=read(path);
 const result=ts.transpileModule(source.toString(),{fileName:path,reportDiagnostics:true,compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022,verbatimModuleSyntax:true}});
 if(result.diagnostics?.length)throw Error('compile diagnostics');
 const compiled=Buffer.from(result.outputText),target=path.replace('/src/','/dist/').replace(/\.ts$/,'.js');
 const destination=new URL(target,out);mkdirSync(new URL('./',destination),{recursive:true});writeFileSync(destination,compiled);
 return {source:path,source_sha256:sha(source),path:target,sha256:sha(compiled),bytes:compiled.length};
});
writeFileSync(new URL('compiled-manifest.json',out),JSON.stringify({source_commit:sourceCommit,base_commit:'a23e522c5dca1f306e7a45ef93b3bddd1f720ba2',files},null,2)+'\n');
console.log(JSON.stringify({source_commit:sourceCommit,modules:files.length}));
