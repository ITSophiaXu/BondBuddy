export function projectGuidance(kind,context={}){
  const workflow=kind==='update'
    ? context.updateMode!=='full'&&context.dataUpdate==='none'
      ? '按本项目已确认的旧版要求保留财务数据的原有日期与口径。'
      : '本项目为全文更新。逐章核对全文，结合本次财务截止日、上传材料及用户补充信息更新需要调整的内容；用户提出的重点或修改要求不缩小全文处理范围。根据材料识别原稿品种和财务年度，不要求用户指定更新章节或年度数量。缺少新数据时保留原有日期和口径并列出缺口，不直接将旧金额换成新日期。'
    : '本项目为全文复核。用户补充的重点与项目信息用于辅助全文核对。';
  return `${workflow}
项目对话中的信息与表单一并处理。拟定发行安排可按用户说明编写；用户补充的授信等经营数据可作为草稿资料使用，但须注明由发行人提供，核对截至日期、金额单位及总额、已使用、未使用金额的勾稽关系。未附证明时在待核实事项中列出，不将其表述为已经审计或外部核验。与审计报告或其他材料冲突时列明差异，不静默覆盖原始证据。复核时不凭一条用户说明直接判定原文数字错误。
是否涉及重大资产重组由系统根据审计报告和附注中的企业合并、合并范围变化、重大资产或股权收购处置等资料，结合适用披露规则判断，并保留来源定位。不能把合并范围变化直接等同于重大资产重组，也不能在材料不足时断言不存在；依据不足列待核实及具体缺失资料，不要求用户回答是或否。
投资者保护、资金用途及相应章节按本次发行品种、实际安排与适用规则核对，不以用户是否填写某个选项作为有无保护条款的依据。项目建设用途结合可研报告、土地证书和相关许可证核对，缺少时列具体资料缺口。`;
}
